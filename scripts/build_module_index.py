# --------------------------------------------------------------------------
# the data
# --------------------------------------------------------------------------


def node_types() -> list[dict]:
    """Every built-in node type, from the generated port catalogue."""
    return json.loads(PORT_SPECS.read_text(encoding="utf-8"))["node_types"]


def providers() -> list[str]:
    """The bundled `ProviderSpec` labels, from the registry itself."""
    sys.path.insert(0, str(BACKEND))
    from openstategraph.providers import builtin_specs

    return [spec.label or spec.name for spec in builtin_specs()]


def cli_verbs() -> list[str]:
    """Top-level verbs the real argparse accepts — never a list typed here."""
    import argparse as _argparse

    sys.path.insert(0, str(BACKEND))
    from openstategraph import cli

    for action in cli.build_parser()._actions:
        if isinstance(action, _argparse._SubParsersAction):
            return sorted(action.choices)
    raise AssertionError("the CLI parser has no subcommands")


def mcp_tools() -> list[str]:
    """`@server.tool(name="…")`, read as text.

    Deliberately not by importing `mcp_server`: that needs the `[mcp]` extra,
    and a documentation generator that only runs on a machine with an optional
    dependency installed is a generator that stops being run.
    """
    source = (PACKAGE / "mcp_server.py").read_text(encoding="utf-8")
    return sorted(set(re.findall(r'@server\.tool\(name="([a-z_]+)"', source)))


def agent_skills() -> list[str]:
    return sorted(p.name for p in (PACKAGE / "agent_skills").iterdir() if p.is_dir())


def _index(relative: str, key: str) -> list:
    return json.loads((PACKAGE / relative).read_text(encoding="utf-8"))[key]


def deeper_link_targets() -> list[str]:
    return sorted({target for _, target, _ in DEEPER})


# --------------------------------------------------------------------------
# rendering
# --------------------------------------------------------------------------


def deeper_for(type_id: str) -> str:
    for prefix, target, label in DEEPER:
        if type_id == prefix or (prefix.endswith(("-", ".")) and type_id.startswith(prefix)):
            return f"[{label}]({target})"
    return f"`openstategraph nodes {type_id}`"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _table(rows: list[dict]) -> list[str]:
    out = [
        "| Type | Name | What it does | Read more |",
        "| --- | --- | --- | --- |",
    ]
    for node in rows:
        mark = " †" if node.get("scope") == "workflow" else ""
        out.append(
            f"| `{node['type']}`{mark} | {_cell(node['label'])} "
            f"| {_cell(node['description'])} | {deeper_for(node['type'])} |"
        )
    return out


def render() -> str:
    types = node_types()
    by_category: dict[str, list[dict]] = {}
    for node in types:
        by_category.setdefault(node["category"], []).append(node)
    for rows in by_category.values():
        rows.sort(key=lambda n: n["type"])

    unknown = set(by_category) - {name for name, _, _ in CATEGORIES}
    if unknown:
        raise SystemExit(
            f"port_specs.json carries categories this generator has no section for: "
            f"{sorted(unknown)} — add one to CATEGORIES in {pathlib.Path(__file__).name}"
        )

    tally = " · ".join(
        f"{name} {len(by_category.get(name, []))}" for name, _, _ in CATEGORIES
    )
    workflow_scoped = [n["type"] for n in types if n.get("scope") == "workflow"]

    lines: list[str] = [
        STAMP,
        "",
        "# Every built-in module",
        "",
        f"This install ships **{len(types)} node types** — the cards you can drop on a",
        "canvas — plus providers, CLI verbs, MCP tools, agent skills, worked examples",
        "and scaffolding templates. This page is the index: one line on each, and a",
        "link to the page that goes deeper where one exists.",
        "",
        "Nothing here is typed by hand. Every row is read out of the data the editor",
        "and the compiler already use, by `scripts/build_module_index.py`, so a type",
        "added, removed or re-described on Monday cannot leave this page telling you",
        "otherwise on Tuesday. If you would rather have it in your terminal,",
        "`openstategraph nodes` prints the same briefs, and `openstategraph nodes",
        "<type>` adds that card's fields and ports.",
        "",
        "## The node vocabulary",
        "",
        f"**{len(types)} types**, by the category the editor's palette groups them under:",
        f"{tally}.",
        "",
        (
            "A card is a *kind of step*. You configure one — a model, a sentence of "
            "rules, an allowlist — rather than writing a class for it; that is the "
            "whole bargain of this product. Drawing them and wiring them is "
            "[on the canvas](on-the-canvas.md); what the wires mean is "
            "[ports and edges](ports-and-edges.md)."
        ),
        "",
    ]

    for name, heading, blurb in CATEGORIES:
        rows = by_category.get(name, [])
        if not rows:
            continue
        lines += [f"### {heading} ({len(rows)})", "", blurb, "", *_table(rows), ""]

    lines += [
        f"† **Workflow-scoped** — {len(workflow_scoped)} of the {len(types)} "
        "(`" + "`, `".join(workflow_scoped) + "`) are contributed by a workflow",
        "package rather than by the install, so they appear only in a project that",
        "carries that package. Your own `tools/*.py` become cards the same way — see",
        "[building an atom](building-an-atom.md).",
        "",
        "## The other built-in families",
        "",
        "Each of these already has a canonical page or a command that prints it, and",
        "a second copy here would be a second thing to keep true. So: the count, from",
        "the same source the software uses, and where to read it.",
        "",
        "| Family | Count | Where its brief lives |",
        "| --- | --- | --- |",
        f"| Model providers | {len(providers())} | "
        "`openstategraph providers` — every provider, the variable it reads, and "
        "whether it is set |",
        f"| CLI verbs | {len(cli_verbs())} | [the CLI reference](cli.md) — one "
        "section each, held against the real parser |",
        f"| MCP tools | {len(mcp_tools())} | [the MCP layer](mcp.md) |",
        f"| Bundled agent skills | {len(agent_skills())} | "
        "[the OpenStateGraph skill](the-openstategraph-skill.md); `init` installs "
        "them into your project |",
        f"| Worked examples | {len(_index('examples/index.json', 'examples'))} | "
        "`openstategraph examples list`, one line each; copy one with "
        "`openstategraph examples copy <slug>` |",
        f"| `new` templates | {len(_index('templates/index.json', 'templates'))} | "
        "`openstategraph new --list-templates`. A template is a *copy* and stops "
        "existing; a mounted package is a *reference* |",
        "",
        "## When this page is wrong",
        "",
        "It cannot be, quietly. `backend/tests/test_documented_modules_match_the_vocabulary.py`",
        "renders the page afresh and compares it byte for byte, so a type with no row,",
        "a row with no type, and a description that has moved are all one red test.",
        "Regenerate with:",
        "",
        "```bash",
        "python3 scripts/build_module_index.py --write",
        "```",
        "",
    ]
    return "\n".join(lines)


def first_difference(committed: str, rendered: str) -> str:
    """A readable excerpt, because a row nobody can open is not a signal."""
    diff = list(
        difflib.unified_diff(
            committed.splitlines(),
            rendered.splitlines(),
            "docs/modules.md (committed)",
            "docs/modules.md (from the data)",
            lineterm="",
            n=1,
        )
    )
    return "\n".join(diff[:40]) or "(no textual difference — trailing bytes?)"


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate docs/modules.md")
    parser.add_argument("--check", action="store_true", help="fail if the page is stale")
    parser.add_argument("--write", action="store_true", help="rewrite the page (default)")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        committed = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if committed != rendered:
            print(first_difference(committed, rendered), file=sys.stderr)
            print(
                "docs/modules.md is out of date — "
                "run python3 scripts/build_module_index.py --write",
                file=sys.stderr,
            )
            return 1
        print(f"docs/modules.md is current ({len(node_types())} node types)")
        return 0

    PAGE.write_text(rendered, encoding="utf-8")
    print(f"wrote docs/modules.md ({len(node_types())} node types, {len(rendered):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
