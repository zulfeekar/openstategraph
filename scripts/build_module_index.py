#!/usr/bin/env python3
"""Regenerate ``docs/modules.md`` — one line per built-in module, from the data.

    python3 scripts/build_module_index.py [--check | --write]

``docs-onramp/04``. The owner's ask was *"a little brief on each built-in module
and what it does, linked."* Looked: **the briefs already exist.**
``backend/openstategraph/compile/port_specs.json`` carries every node type with
a ``label``, a ``description``, a ``category`` and a ``scope``, and not one of
them is missing a description. ``openstategraph nodes`` prints all of them, one
line each, and is the best summary of this product's vocabulary anywhere in the
repository.

What did not exist was a **page**. On 2026-09-05 thirteen of the forty-three
types were named — by id *or* by display label — in no file under ``docs/``, and
thirty were named in neither form in ``docs/on-the-canvas.md``, the page
``docs/README.md`` routes *"understand what I am drawing"* to. So the gap was
routing, not content, and the fix is a page that **derives** the content rather
than restating it.

**Generated, not typed**, for two reasons and the second is the one that binds:

- a hand-kept second copy of forty-three descriptions is ``CLAUDE.md``'s
  duplication rule broken — the field schema is declared once and card,
  inspector, defaults and validation all derive from it, and a documentation
  page has no claim to be the exception;
- it would be stale within a week. The vocabulary moved by four types in the
  month before this page existed, and nothing would have said so.

Every count on the page is printed from the data this script just read, so the
page states no number a human has to keep true — ``CLAUDE.md``'s rule that a
number in prose has no way to fail, applied to a page whose entire subject is
counts.

## What is derived, and from where

Nothing here restates a brief that has an owner elsewhere:

===========================  ==================================================
node types (43)              ``compile/port_specs.json`` — id, label,
                             description, category, scope
providers                    ``openstategraph.providers.builtin_specs()``
CLI verbs                    ``cli.build_parser()``, the real argparse
MCP tools                    ``@server.tool(name=…)`` in ``mcp_server.py``,
                             read as text so this script needs no ``[mcp]``
bundled agent skills         the directories under ``openstategraph/agent_skills/``
worked examples              ``examples/index.json``
``new`` templates            ``templates/index.json``
===========================  ==================================================

The five families after the first get **one row each**, not a copy of their
pages. ``docs/cli.md`` is 20/20 against the parser and ``docs/mcp.md`` is 18/18
against the server; both are canonical and a second enumeration here would make
``docs/README.md``'s promise of a single place false while satisfying a gate.
What this page adds for them is a count that cannot be wrong and a link.

## The one hand-written table, named

``DEEPER`` below maps a type — or a prefix of one — onto the page that goes
further than a one-line brief. It is hand-written because *"which page explains
this properly"* is a judgement and no field in the data carries it. Scanning
``docs/`` for each type id was priced and rejected: it would make this page's
bytes a function of every other page's prose, so an unrelated sentence added to
``patterns.md`` would fail the drift gate in CI with a diff about node types.
The cost of the judgement is two assertions in
``backend/tests/test_documented_modules_match_the_vocabulary.py``: the target
exists, **and** the target names that module by id or by label outside a fenced
block. Existence alone was not enough, and ``docs-onramp/11`` is the bill —
every link resolved, and 31 of the 43 landed on a page that never mentioned the
card the reader had just clicked. Naming is judged on prose only, because the
row that exposed this was ``tool.platform-read-file``: its id sat in a comment
inside an example document on ``docs/mcp.md``, and nothing written *to* a reader
on that page said what the tool read.

Types with no entry fall back to ``openstategraph nodes <type>``, which prints
the fields and ports as well as the brief, and is never stale by construction.
"""

