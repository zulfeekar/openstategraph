# SQL — the first concrete: one topic per table of each configured database.
# ---------------------------------------------------------------------------


def databases_in_document(document: dict[str, Any], workflows_root: Path) -> list[Path]:
    """Every SQL database this document's tool nodes point at.

    Read from the same fields the SQL Explorer nodes are configured with
    (``tool.sql-*``'s ``database``), plus the bundled Chinook database when
    any ``tool.chinook-*`` node is present. Jailed to the workflows root and
    limited to files that exist — a bad path is a skipped source, never an
    escape hatch.
    """
    root = workflows_root.resolve()
    found: list[Path] = []
    for node in document.get("nodes") or []:
        node_type = str(node.get("type") or "")
        relative = ""
        if node_type.startswith(_SQL_NODE_PREFIX):
            relative = str((node.get("data") or {}).get("database") or "").strip()
        elif node_type.startswith(_CHINOOK_NODE_PREFIX):
            relative = _CHINOOK_DATABASE
        if not relative:
            continue
        candidate = (root / relative).resolve()
        try:
            candidate.relative_to(root)
        except ValueError:
            continue
        if candidate.is_file() and candidate not in found:
            found.append(candidate)
    return found


def _connect(path: Path) -> sqlite3.Connection:
    return sqlite3.connect(f"file:{path}?mode=ro", uri=True)


def _table_names(conn: sqlite3.Connection) -> list[str]:
    return [
        r[0]
        for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name"
        )
    ]


def table_brief(database: Path, table: str, sample_rows: int = 5) -> str:
    """Everything the model needs about one table: full schema (columns,
    types, PKs, FKs **both directions**) and a small data sample."""
    with _connect(database) as conn:
        columns = [
            f"- {r[1]} ({r[2] or 'ANY'})" + (" PRIMARY KEY" if r[5] else "")
            for r in conn.execute(f'PRAGMA table_info("{table}")')
        ]
        outbound = [
            f"- JOIN rule: {table}.{r[3]} references {r[2]}.{r[4]}"
            for r in conn.execute(f'PRAGMA foreign_key_list("{table}")')
        ]
        inbound = []
        for other in _table_names(conn):
            if other == table:
                continue
            for r in conn.execute(f'PRAGMA foreign_key_list("{other}")'):
                if r[2] == table:
                    inbound.append(
                        f"- JOIN rule (referenced by): {other}.{r[3]} references {table}.{r[4]}"
                    )
        cursor = conn.execute(f'SELECT * FROM "{table}" LIMIT {int(sample_rows)}')
        headers = [d[0] for d in cursor.description or []]
        sample = [
            "| " + " | ".join(headers) + " |",
            "| " + " | ".join("---" for _ in headers) + " |",
            *("| " + " | ".join(str(c) for c in row) + " |" for row in cursor.fetchall()),
        ]
    parts = ["## Columns", *columns]
    if outbound:
        parts += ["\n## Foreign keys (outbound)", *outbound]
    if inbound:
        parts += ["\n## Foreign keys (inbound)", *inbound]
    parts += ["\n## Data sample", *sample]
    return "\n".join(parts)


class SqlKnowledgeBuilder(BaseKnowledgeBuilder):
    """One topic per table of every database the workflow's SQL tools use."""

    source_kind = "sql"

    def discover(
        self, workflow_dir: Path, document: dict[str, Any], workflows_root: Path
    ) -> list[KnowledgeTopic]:
        topics: list[KnowledgeTopic] = []
        seen: set[str] = set()
        for database in databases_in_document(document, workflows_root):
            with _connect(database) as conn:
                tables = _table_names(conn)
            for table in tables:
                key = BaseKnowledge.normalize(table)
                if key in seen:
                    continue  # same-named table in a second database: first wins
                seen.add(key)
                topics.append(KnowledgeTopic(name=table, brief=table_brief(database, table)))
        return topics


#: The extension point: register a builder here, never edit the endpoint.
BUILDERS: list[BaseKnowledgeBuilder] = [SqlKnowledgeBuilder()]


