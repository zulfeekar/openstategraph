# SQL — one topic per table, generic over engines via the adapter seam.
# ---------------------------------------------------------------------------


def databases_in_document(document: dict[str, Any], workflows_root: Path) -> list[Path]:
    """Every SQLite database file this document's tool nodes point at.

    Kept for the SQLite path (jailed to the workflows root, limited to files
    that exist — a bad path is a skipped source, never an escape hatch).
    URL-schemed refs are the adapter seam's business: see
    ``sql_sources_in_document``.
    """
    return [
        workflows_root.resolve() / ref
        for ref, engine in sql_sources_in_document(document, workflows_root)
        if engine == "sqlite"
    ]


def sql_sources_in_document(
    document: dict[str, Any], workflows_root: Path
) -> list[tuple[str, str]]:
    """Every recognized SQL source in the document, as ``(ref, engine)``.

    Recognition reads the wiring (``knowledge_engines.recognize``): a bare
    path is SQLite (jailed to the workflows root, must exist; the ref is
    normalized to root-relative), a ``postgres://``/``mssql://`` URL names
    its engine and is passed through for the adapter to open.
    """
    root = workflows_root.resolve()
    found: list[tuple[str, str]] = []
    seen: set[str] = set()
    for node in document.get("nodes") or []:
        node_type = str(node.get("type") or "")
        ref = ""
        if node_type.startswith(_SQL_NODE_PREFIX):
            ref = str((node.get("data") or {}).get("database") or "").strip()
        elif node_type.startswith(_CHINOOK_NODE_PREFIX):
            ref = _CHINOOK_DATABASE
        if not ref:
            continue
        engine = recognize(ref)
        if engine is None:
            continue
        if engine == "sqlite" and "://" not in ref:
            candidate = (root / ref).resolve()
            try:
                candidate.relative_to(root)
            except ValueError:
                continue
            if not candidate.is_file():
                continue
            ref = str(candidate.relative_to(root))
        if ref in seen:
            continue
        seen.add(ref)
        found.append((ref, engine))
    return found


def table_brief(database: Path, table: str, sample_rows: int = 5) -> str:
    """One SQLite table's brief — schema (FKs both directions) + sample.

    A thin veneer over the SQLite adapter, kept as the module's historical
    public name."""
    return SqliteEngineAdapter().table_brief(str(database), table, sample_rows)


class SqlKnowledgeBuilder(BaseKnowledgeBuilder):
    """One topic per table of every SQL source the workflow's tools use.

    Engines are the adapter seam's business (``knowledge_engines``): this
    builder recognizes refs from the wiring, asks the matching adapter for
    tables and briefs, and reports a recognized source whose driver is
    missing as a warning — never a crash, never a silent skip.
    """

    source_kind = "sql"

    def discover(
        self, workflow_dir: Path, document: dict[str, Any], workflows_root: Path
    ) -> Discovery:
        root = workflows_root.resolve()
        topics: list[KnowledgeTopic] = []
        warnings: list[str] = []
        seen: set[str] = set()
        for ref, engine in sql_sources_in_document(document, workflows_root):
            adapter = ENGINE_ADAPTERS[engine]
            usable, warning = adapter.available()
            if not usable:
                warnings.append(
                    f"{ref}: recognized as {engine}, but unavailable — {warning}"
                )
                continue
            connection_ref = str(root / ref) if engine == "sqlite" else ref
            for table in adapter.list_tables(connection_ref):
                key = BaseKnowledge.normalize(table)
                if key in seen:
                    continue  # same-named table in a second source: first wins
                seen.add(key)
                topics.append(
                    KnowledgeTopic(
                        name=table,
                        brief=adapter.table_brief(connection_ref, table),
                        provenance=(f"table {table} of {ref} ({engine} schema + sample)",),
                    )
                )
        return Discovery(topics=topics, warnings=warnings)


